-- ---------------------------------------------------------------------
-- ETL CONTROL: logging, checkpoints, watermarks, data quality, dead letter
-- ---------------------------------------------------------------------

CREATE SCHEMA "etl";

-- One row per pipeline run. Mode: incremental / full. Status: running / success / failed.
CREATE TABLE "etl"."Run" (
  "RunID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "AsOfDate" date NOT NULL,
  "Mode" varchar(12) NOT NULL,
  "TriggeredBy" varchar(20),
  "Status" varchar(10) NOT NULL,
  "StartedAt" timestamp NOT NULL,
  "FinishedAt" timestamp,
  "Message" text
);

-- One row per step attempt = the checkpoint. A resumed run skips steps with a success row.
CREATE TABLE "etl"."StepRun" (
  "StepRunID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RunID" int NOT NULL,
  "Step" varchar(40) NOT NULL,
  "Attempt" smallint NOT NULL,
  "Status" varchar(10) NOT NULL,
  "StartedAt" timestamp NOT NULL,
  "FinishedAt" timestamp,
  "DurationSec" decimal(10,3),
  "RowsIn" int,
  "RowsOut" int,
  "Metrics" jsonb,
  "Error" text
);

-- Incremental extraction: highest UpdatedAt already loaded, per source table.
-- Moved forward only when a whole run has succeeded. ExtractedAt = time of the CRM
-- snapshot of that run: the 5-minute overlap for late commits reaches back from it, so a
-- run draining a backlog (watermark far behind the snapshot) re-reads nothing.
CREATE TABLE "etl"."Watermark" (
  "SourceTable" varchar(60) PRIMARY KEY,
  "LastUpdatedAt" timestamp,
  "ExtractedAt" timestamp,
  "LastRunID" int,
  "ChangedAt" timestamp
);

-- Data-quality rules as metadata. Kind: row (checked per extracted row) / set (checked
-- on the whole staging table). Severity: reject (row goes to dead letter), warn, block (run stops).
CREATE TABLE "etl"."DqRule" (
  "RuleID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RuleName" varchar(60) UNIQUE NOT NULL,
  "TableName" varchar(60) NOT NULL,
  "Kind" varchar(5) NOT NULL,
  "Severity" varchar(6) NOT NULL,
  "Description" varchar(255),
  "CheckSql" text NOT NULL,
  "IsActive" char(1) NOT NULL
);

CREATE TABLE "etl"."DqResult" (
  "DqResultID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RunID" int NOT NULL,
  "RuleID" int NOT NULL,
  "RowsChecked" int,
  "RowsFailed" int,
  "Passed" char(1),
  "CheckedAt" timestamp
);

-- Dead letter: rows that failed a reject rule, kept with their payload for investigation.
-- ResolvedRunID = the run in which a corrected version of the row was loaded.
CREATE TABLE "etl"."RejectedRow" (
  "RejectedRowID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RunID" int NOT NULL,
  "RuleID" int NOT NULL,
  "SourceTable" varchar(60) NOT NULL,
  "SourceKey" int NOT NULL,
  "Payload" jsonb,
  "RejectedAt" timestamp,
  "ResolvedRunID" int
);

CREATE TABLE "etl"."Alert" (
  "AlertID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RunID" int,
  "Severity" varchar(10) NOT NULL,
  "Message" text NOT NULL,
  "CreatedAt" timestamp NOT NULL
);

CREATE INDEX ON "etl"."StepRun" ("RunID", "Step");

CREATE INDEX ON "etl"."RejectedRow" ("SourceTable", "SourceKey");

ALTER TABLE "etl"."StepRun" ADD FOREIGN KEY ("RunID") REFERENCES "etl"."Run" ("RunID");

ALTER TABLE "etl"."Watermark" ADD FOREIGN KEY ("LastRunID") REFERENCES "etl"."Run" ("RunID");

ALTER TABLE "etl"."DqResult" ADD FOREIGN KEY ("RunID") REFERENCES "etl"."Run" ("RunID");

ALTER TABLE "etl"."DqResult" ADD FOREIGN KEY ("RuleID") REFERENCES "etl"."DqRule" ("RuleID");

ALTER TABLE "etl"."RejectedRow" ADD FOREIGN KEY ("RunID") REFERENCES "etl"."Run" ("RunID");

ALTER TABLE "etl"."RejectedRow" ADD FOREIGN KEY ("RuleID") REFERENCES "etl"."DqRule" ("RuleID");

ALTER TABLE "etl"."Alert" ADD FOREIGN KEY ("RunID") REFERENCES "etl"."Run" ("RunID");
