-- =====================================================================
-- Aisle & Co. — Data Warehouse v7 (target of the ETL pipeline)
-- = DW v6 lean star schema, revised after review (4 dims + 3 facts):
--     * ratios are no longer stored (UtilizationRate, QuoteShareOfBudget); the mart
--       views compute them from their parts, so a dashboard cannot sum or average them
--     * the inquiry status / stage / lost-reason labels moved from FactInquiry into the
--       junk dimension DimInquiryOutcome; InquiryStatus, IsLost and IsOpen were dropped
--   + "stg"  : persistent staging = cleaned replica of the 9 CRM tables the
--              warehouse needs, without personal data (Silver zone)
--   + "etl"  : pipeline control tables: runs, steps (checkpoints), watermarks,
--              data-quality rules and results, rejected rows (dead letter), alerts
-- Not in this file (dbdiagram cannot import them): helper functions, the
-- transient landing tables and the KPI views (sql/dw_v7_functions.sql,
-- sql/dw_v7_mart_views.sql).
-- Import into dbdiagram.io as PostgreSQL.
-- =====================================================================
-- (DW v6 conventions repeated below: surrogate keys, -1 = Unknown, Type 1 dims,
--  frozen weekly rows, no customer personal data, [A]/[N] additivity.)

CREATE SCHEMA "dim";

CREATE SCHEMA "fact";

-- ---------------------------------------------------------------------
-- DIMENSIONS
-- ---------------------------------------------------------------------

-- Calendar, role-played as inquiry, requested, consultation, quote, booking,
-- event and week-start dates. AuspiciousDate folded in.
CREATE TABLE "dim"."DimDate" (
  "DateKey" int PRIMARY KEY,
  "FullDate" date UNIQUE NOT NULL,
  "DayName" varchar(10),
  "IsWeekend" char(1),
  "WeekStartDate" date,
  "MonthNumber" smallint,
  "MonthName" varchar(10),
  "YearMonth" char(7),
  "Quarter" smallint,
  "CalendarYear" smallint,
  "BuddhistYear" smallint,
  "IsHighSeason" char(1),
  "IsBuddhistLent" char(1),
  "IsAuspicious" char(1),
  "AuspiciousLevel" varchar(10)
);

-- Type 1. Each OLTP PackageID is a price version; PackageFamily rolls them up.
CREATE TABLE "dim"."DimPackage" (
  "PackageKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PackageID" int UNIQUE NOT NULL,
  "PackageFamily" varchar(100),
  "PackageType" varchar(20),
  "ServiceFeeType" varchar(20),
  "IsCurrentVersion" char(1)
);

-- Type 1. Capacity numbers are NOT here: they are copied into each weekly row.
CREATE TABLE "dim"."DimEmployee" (
  "EmployeeKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EmployeeID" int UNIQUE NOT NULL,
  "FullName" varchar(200),
  "RoleName" varchar(100),
  "EmploymentType" varchar(20),
  "EmployeeStatus" varchar(10)
);

-- Junk dimension: every combination of outcome labels that occurs (a few dozen rows).
-- Loaded by the fact_inquiry step. Outcome: Booked / Lost / Cancelled /
-- Converted, no event / Open. FurthestStage: New / Contacted / Consultation / Quoted / Booked.
-- ClosedBy: Sales / AutoRule. 'N/A' when the inquiry has no value.
CREATE TABLE "dim"."DimInquiryOutcome" (
  "OutcomeKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Outcome" varchar(20) NOT NULL DEFAULT 'N/A',
  "FurthestStage" varchar(20) NOT NULL DEFAULT 'N/A',
  "ClosedBy" varchar(10) NOT NULL DEFAULT 'N/A',
  "LostReason" varchar(100) NOT NULL DEFAULT 'N/A'
);

-- ---------------------------------------------------------------------
-- FACTS
-- ---------------------------------------------------------------------

-- Problems 2 and 1 (peak acceptance, turned-away demand).
-- Accumulating snapshot, grain = 1 Inquiry. Stage date keys -1 until reached.
--   ResponseTimeMinutes : first Staff message - first Customer message (ChatMessage;
--     Bot ignored). Band 'In person' for kiosk / walk-in, 'Not logged' when a chat
--     lead has no logged staff reply.
--   FirstResponderEmployeeKey : staff member who sent that first reply (-1 if none).
--   BudgetMidpoint : midpoint of the couple's BudgetRange in THB (e.g. 500k-1M -> 750,000).
--     Quote share of budget = QuotedAmount / BudgetMidpoint is computed in mart.v_inquiry.
--   OutcomeKey : outcome labels (DimInquiryOutcome). Outcome = 'Open' means still
--     undecided; exclude or group by inquiry month when reading recent conversion.
-- [A] InquiryCount, Is* flags, QuotedAmount
-- [N] ResponseTimeMinutes, Days*, BudgetMidpoint (average / median)
CREATE TABLE "fact"."FactInquiry" (
  "InquiryFactKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "InquiryID" int UNIQUE NOT NULL,
  "ConvertedEventID" int,
  "InquiryDateKey" int NOT NULL,
  "ConsultationDateKey" int NOT NULL,
  "QuotedDateKey" int NOT NULL,
  "RequestedEventDateKey" int NOT NULL,
  "IndicativePackageKey" int NOT NULL,
  "FirstResponderEmployeeKey" int NOT NULL,
  "OutcomeKey" int NOT NULL,
  "ChannelName" varchar(50) NOT NULL DEFAULT 'N/A',
  "ChannelType" varchar(10) NOT NULL DEFAULT 'N/A',
  "BudgetRange" varchar(30) NOT NULL DEFAULT 'N/A',
  "ResponseTimeBand" varchar(20) NOT NULL DEFAULT 'N/A',
  "InquiryCount" smallint,
  "IsConsulted" smallint,
  "IsQuoted" smallint,
  "IsConverted" smallint,
  "QuotedAmount" decimal(12,2),
  "BudgetMidpoint" decimal(12,2),
  "ResponseTimeMinutes" int,
  "DaysToConsultation" int,
  "DaysConsultationToQuote" int,
  "DaysQuoteToBooking" int,
  "DaysToConvert" int
);

-- Problem 1 (demand by event date, hours per wedding). Grain = 1 Event.
-- Hours split: per assignment up to 12 h = event day, the rest = planning.
-- [A] EventCount, IsCancelled, GuestCount, AgreedPackagePrice, StaffCount, *Hours
-- [N] BookingLeadTimeDays
CREATE TABLE "fact"."FactEventBooking" (
  "EventFactKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EventID" int UNIQUE NOT NULL,
  "InquiryID" int,
  "BookingDateKey" int NOT NULL,
  "EventDateKey" int NOT NULL,
  "PackageKey" int NOT NULL,
  "EventStatus" varchar(20) NOT NULL DEFAULT 'N/A',
  "ComplexityLevel" varchar(10) NOT NULL DEFAULT 'N/A',
  "EventCount" smallint,
  "IsCancelled" smallint,
  "GuestCount" int,
  "AgreedPackagePrice" decimal(12,2),
  "BookingLeadTimeDays" int,
  "StaffCount" smallint,
  "PlanningHours" decimal(10,2),
  "EventDayHours" decimal(10,2),
  "TotalStaffHours" decimal(10,2)
);

-- Problem 1 (utilization, overtime, concurrency). Periodic snapshot,
-- grain = 1 Employee x 1 ISO week, idle weeks included. Cancelled events excluded.
-- Planning hours are spread evenly from the assignment week to the week before
-- the event (event week if the same week or assigned later); event-day hours go
-- in the event week. StandardWeeklyHours / MaxConcurrentEvents = values that
-- applied that week. Rows for weeks that have ended are frozen.
-- Utilization = sum(TotalAssignedHours) / sum(StandardWeeklyHours), computed in
-- mart.v_weekly_workload (not stored, so it is never summed or averaged by mistake).
-- [A] PlanningHours, EventDayHours, TotalAssignedHours, OvertimeHours, IsOverCapacity
-- [N] ActiveEvents, StandardWeeklyHours, MaxConcurrentEvents
CREATE TABLE "fact"."FactEmployeeWeeklyWorkload" (
  "EmployeeWeekKey" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "WeekStartDateKey" int NOT NULL,
  "EmployeeKey" int NOT NULL,
  "PlanningHours" decimal(8,2),
  "EventDayHours" decimal(8,2),
  "TotalAssignedHours" decimal(8,2),
  "StandardWeeklyHours" decimal(5,2),
  "OvertimeHours" decimal(8,2),
  "ActiveEvents" smallint,
  "MaxConcurrentEvents" smallint,
  "IsOverCapacity" smallint
);

