-- =====================================================================
-- Aisle & Co. — OLTP v4 "lean" (12 tables: 8 master + 4 transaction)
-- Scope: Business Problem 1 (Seasonal Demand & Capacity) and
--        Business Problem 2 (High Inquiry & Low Conversion) only.
--
-- How the data arrives
--   * Chat leads: LINE / Messenger / Instagram send each customer message to
--     our server by webhook (time + platform user ID). Staff reply from the
--     shared inbox, so replies are logged too. Message TEXT stays in the raw
--     data zone; ChatMessage keeps only who / when / direction.
--   * Fair leads: tablet form at the booth (channel Wedding Fair).
--   * Walk-in and referral: entered by sales in the CRM.
--   * Channel source: platform (Messenger -> Facebook, Instagram -> Instagram)
--     or the code pre-typed by a channel-specific LINE link / QR
--     (MarketingChannel.TrackingCode, e.g. #TIKTOK, #FAIR, #WEB).
--
-- System-set Inquiry fields (never typed by staff)
--   ContactedDate / ResponseTimeMinutes : from the first Staff message after the
--     first Customer message (Bot auto-replies ignored). NULL for in-person leads.
--   ClosedBy = 'AutoRule' + LostReason 'No reply' : 30 days without a customer message.
-- Sales-set: consultation / quote (CRM actions), QuotedAmount, LostReason when the
--   couple says no: Price, Date unavailable, Chose competitor, Scope mismatch, Budget changed.
--
-- Changes vs v3 (scope cut to Problems 1 and 2): removed MarketingCampaign,
-- CampaignPerformanceLog, OfflineEventDetail, PackageService, Department,
-- VendorType, Vendor, VendorService, EventVendorAssignment, ClientPayment,
-- VendorPayment. Added Inquiry.QuotedAmount and MarketingChannel.TrackingCode.
-- Dropped columns no longer used: Inquiry.CampaignID/Note, Event.DiscountAmount/
-- Budget/AuspiciousDateID (auspicious comes from the calendar by date),
-- Employee.DepartmentID/Phone/Email, Package.Description, ChatMessage.MessageType.
-- =====================================================================

CREATE SCHEMA "master";

CREATE SCHEMA "transaction";

-- ---------- master ----------

CREATE TABLE "master"."Customer" (
  "CustomerID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Address" varchar(255),
  "CreatedDate" timestamp
);

CREATE TABLE "master"."CustomerContact" (
  "CustomerContactID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerID" int NOT NULL,
  "ContactName" varchar(100),
  "ContactTitle" varchar(20),
  "Phone" varchar(20),
  "Email" varchar(100),
  "IsPrimaryContact" char(1)
);

CREATE TABLE "master"."CustomerChannelAccount" (
  "CustomerAccountID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerID" int NOT NULL,
  "Platform" varchar(20) NOT NULL,
  "ExternalUserID" varchar(64) NOT NULL,
  "DisplayName" varchar(100),
  "FirstSeenAt" timestamp,
  "FirstTrackingCode" varchar(30)
);

CREATE TABLE "master"."MarketingChannel" (
  "ChannelID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ChannelName" varchar(50),
  "ChannelType" varchar(10),
  "TrackingCode" varchar(30) UNIQUE,
  "Status" varchar(10)
);

CREATE TABLE "master"."Package" (
  "PackageID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PackageName" varchar(100),
  "PackageType" varchar(20),
  "BasePrice" decimal(12,2),
  "ServiceFeeType" varchar(20),
  "ServiceFeeRate" decimal(5,2),
  "EffectiveFrom" date,
  "EffectiveTo" date,
  "Status" varchar(10)
);

CREATE TABLE "master"."EmployeeRole" (
  "RoleID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RoleName" varchar(100) UNIQUE,
  "Status" varchar(10)
);

CREATE TABLE "master"."Employee" (
  "EmployeeID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RoleID" int NOT NULL,
  "EmployeeCode" varchar(20) UNIQUE,
  "FirstName" varchar(100),
  "LastName" varchar(100),
  "EmploymentType" varchar(20),
  "HireDate" date,
  "StandardWeeklyHours" decimal(5,2),
  "MaxConcurrentEvents" int,
  "Status" varchar(10)
);

CREATE TABLE "master"."AuspiciousDate" (
  "AuspiciousDateID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CalendarDate" date,
  "DateType" varchar(20),
  "AuspiciousLevel" varchar(10),
  "Description" varchar(255)
);

-- ---------- transaction ----------

CREATE TABLE "transaction"."Inquiry" (
  "InquiryID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerID" int NOT NULL,
  "ChannelID" int NOT NULL,
  "IndicativePackageID" int,
  "InquiryDate" timestamp,
  "RequestedEventDate" date,
  "BudgetRange" varchar(30),
  "ResponseTimeMinutes" int,
  "ContactedDate" timestamp,
  "ConsultationDate" timestamp,
  "QuotedDate" timestamp,
  "QuotedAmount" decimal(12,2),
  "ClosedDate" timestamp,
  "ClosedBy" varchar(10),
  "Status" varchar(20),
  "LostReason" varchar(100)
);

CREATE TABLE "transaction"."ChatMessage" (
  "ChatMessageID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerAccountID" int NOT NULL,
  "InquiryID" int,
  "PlatformMessageID" varchar(64) UNIQUE,
  "SentAt" timestamp NOT NULL,
  "Direction" varchar(3) NOT NULL,
  "SenderType" varchar(10) NOT NULL,
  "EmployeeID" int,
  "TrackingCode" varchar(30)
);

CREATE TABLE "transaction"."Event" (
  "EventID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "CustomerID" int NOT NULL,
  "InquiryID" int UNIQUE,
  "PackageID" int NOT NULL,
  "EventDate" date,
  "GuestCount" int,
  "ComplexityLevel" varchar(10),
  "AgreedPackagePrice" decimal(12,2),
  "Status" varchar(20),
  "CreatedDate" timestamp
);

CREATE TABLE "transaction"."EventEmployeeAssignment" (
  "EventEmployeeAssignmentID" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EventID" int NOT NULL,
  "EmployeeID" int NOT NULL,
  "AssignmentRole" varchar(50),
  "AssignedDate" timestamp,
  "WorkloadHours" decimal(8,2),
  "IsLead" char(1),
  "Status" varchar(20)
);

-- ---------- keys ----------

CREATE UNIQUE INDEX ON "master"."AuspiciousDate" ("CalendarDate", "DateType");

CREATE UNIQUE INDEX ON "master"."CustomerChannelAccount" ("Platform", "ExternalUserID");

ALTER TABLE "master"."CustomerContact" ADD FOREIGN KEY ("CustomerID") REFERENCES "master"."Customer" ("CustomerID");

ALTER TABLE "master"."CustomerChannelAccount" ADD FOREIGN KEY ("CustomerID") REFERENCES "master"."Customer" ("CustomerID");

ALTER TABLE "master"."Employee" ADD FOREIGN KEY ("RoleID") REFERENCES "master"."EmployeeRole" ("RoleID");

ALTER TABLE "transaction"."Inquiry" ADD FOREIGN KEY ("CustomerID") REFERENCES "master"."Customer" ("CustomerID");

ALTER TABLE "transaction"."Inquiry" ADD FOREIGN KEY ("ChannelID") REFERENCES "master"."MarketingChannel" ("ChannelID");

ALTER TABLE "transaction"."Inquiry" ADD FOREIGN KEY ("IndicativePackageID") REFERENCES "master"."Package" ("PackageID");

ALTER TABLE "transaction"."ChatMessage" ADD FOREIGN KEY ("CustomerAccountID") REFERENCES "master"."CustomerChannelAccount" ("CustomerAccountID");

ALTER TABLE "transaction"."ChatMessage" ADD FOREIGN KEY ("InquiryID") REFERENCES "transaction"."Inquiry" ("InquiryID");

ALTER TABLE "transaction"."ChatMessage" ADD FOREIGN KEY ("EmployeeID") REFERENCES "master"."Employee" ("EmployeeID");

ALTER TABLE "transaction"."Event" ADD FOREIGN KEY ("CustomerID") REFERENCES "master"."Customer" ("CustomerID");

ALTER TABLE "transaction"."Event" ADD FOREIGN KEY ("InquiryID") REFERENCES "transaction"."Inquiry" ("InquiryID");

ALTER TABLE "transaction"."Event" ADD FOREIGN KEY ("PackageID") REFERENCES "master"."Package" ("PackageID");

ALTER TABLE "transaction"."EventEmployeeAssignment" ADD FOREIGN KEY ("EventID") REFERENCES "transaction"."Event" ("EventID");

ALTER TABLE "transaction"."EventEmployeeAssignment" ADD FOREIGN KEY ("EmployeeID") REFERENCES "master"."Employee" ("EmployeeID");
